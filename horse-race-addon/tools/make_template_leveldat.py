"""Create template/level.dat: a flat desert world (biome: desert) for the world template.

The base file is a level.dat written by Bedrock Dedicated Server 1.26.63 for a flat world.
Only the fields below are changed; the world itself is generated by the game.
Usage: python3 tools/make_template_leveldat.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bnbt  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "template", "base_level.dat")
DST = os.path.join(ROOT, "template", "level.dat")

LAYERS = {
    "biome_id": 2,  # desert
    "block_layers": [
        {"block_name": "minecraft:bedrock", "count": 1},
        {"block_name": "minecraft:deepslate", "count": 60},
        {"block_name": "minecraft:stone", "count": 60},
        {"block_name": "minecraft:sandstone", "count": 4},
        {"block_name": "minecraft:sand", "count": 3},
    ],
    "encoding_version": 6,
    "structure_options": None,
    "world_version": "version.post_1_18",
}


def main():
    ver, root = bnbt.read_level_dat(SRC)
    v = root.v
    T = bnbt.Tag
    v["LevelName"] = T(bnbt.TAG_STRING, "大陸横断ホースレース")
    v["Generator"] = T(bnbt.TAG_INT, 2)  # flat
    v["FlatWorldLayers"] = T(bnbt.TAG_STRING, json.dumps(LAYERS, separators=(",", ":")) + "\n")
    v["GameType"] = T(bnbt.TAG_INT, 0)  # survival
    v["Difficulty"] = T(bnbt.TAG_INT, 2)  # normal
    v["showcoordinates"] = T(bnbt.TAG_BYTE, 1)  # coordinates help navigating to checkpoints
    v["doweathercycle"] = T(bnbt.TAG_BYTE, 0)
    v["Time"] = T(bnbt.TAG_LONG, 1000)
    v["currentTick"] = T(bnbt.TAG_LONG, 0)
    v["LastPlayed"] = T(bnbt.TAG_LONG, 0)
    v["worldStartCount"] = T(bnbt.TAG_LONG, 0)
    v["SpawnX"] = T(bnbt.TAG_INT, 0)
    v["SpawnY"] = T(bnbt.TAG_INT, 32767)
    v["SpawnZ"] = T(bnbt.TAG_INT, 0)
    # allow every client that can run the add-on (Script API 2.1.0 = 1.21.100+)
    ver_list = lambda a: T(bnbt.TAG_LIST, [T(bnbt.TAG_INT, n) for n in a], bnbt.TAG_INT)  # noqa: E731
    v["MinimumCompatibleClientVersion"] = ver_list([1, 21, 100, 0, 0])
    v["lastOpenedWithVersion"] = ver_list([1, 21, 100, 0, 0])
    v["InventoryVersion"] = T(bnbt.TAG_STRING, "1.21.100")
    v["hasBeenLoadedInCreative"] = T(bnbt.TAG_BYTE, 0)
    v["cheatsEnabled"] = T(bnbt.TAG_BYTE, 0)
    bnbt.write_level_dat(DST, ver, root)
    print("wrote", DST)


if __name__ == "__main__":
    main()
